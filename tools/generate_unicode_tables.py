#!/usr/bin/env python3
"""Generate compact Unicode tables used by the native MuLaCover tokenizer.

The checked-in result keeps native builds independent of Python. Re-run this
script deliberately when updating the Unicode database version.
"""

from __future__ import annotations

import unicodedata
import importlib.metadata
from tokenizers import Regex, normalizers


def ranges_for(predicate):
    result = []
    start = None
    previous = None
    for codepoint in range(0x110000):
        if predicate(codepoint):
            if start is None:
                start = codepoint
            previous = codepoint
        elif start is not None:
            result.append((start, previous))
            start = previous = None
    if start is not None:
        result.append((start, previous))
    return result


def valued_ranges(value_of):
    result = []
    start = 0
    previous = value_of(0)
    for codepoint in range(1, 0x110000):
        value = value_of(codepoint)
        if value != previous:
            if previous:
                result.append((start, codepoint - 1, previous))
            start = codepoint
            previous = value
    if previous:
        result.append((start, 0x10FFFF, previous))
    return result


def emit_pairs(name, values):
    print(f"inline constexpr CodepointRange {name}[] = {{")
    for first, last in values:
        print(f"    {{0x{first:X}, 0x{last:X}}},")
    print("};")


def main():
    if unicodedata.unidata_version!='13.0.0' or importlib.metadata.version('tokenizers')!='0.22.1':
        raise RuntimeError('Regenerate only in the pinned reference image (Python Unicode 13.0.0, tokenizers 0.22.1)')
    # Extract regex categories and normalization from the exact Rust tokenizer
    # used by the oracle, rather than guessing its Unicode version from Python.
    alphabet = ''.join(chr(cp) for cp in range(0x110000) if not 0xD800<=cp<=0xDFFF)
    letter_set=set(normalizers.Replace(Regex(r'\P{L}'),'').normalize_str(alphabet))
    number_set=set(normalizers.Replace(Regex(r'\P{N}'),'').normalize_str(alphabet))
    letters = ranges_for(lambda cp: chr(cp) in letter_set)
    numbers = ranges_for(lambda cp: chr(cp) in number_set)
    nfd=normalizers.NFD().normalize_str; nfc=normalizers.NFC().normalize_str
    # Native NFC needs only ordering/equality of canonical combining classes.
    # Discover post-Python-database marks using Rust NFD, insert them into the
    # class order, then emit compact ordinal ranks (not literal CCC numbers).
    representatives={}; known={}
    for cp in range(0x110000):
        value=unicodedata.combining(chr(cp))
        if value:known[cp]=value;representatives.setdefault(value,chr(cp))
    classes=[(value,representatives[value]) for value in sorted(representatives)]
    extra={}
    def compare(a,b):
        ab=nfd(a+b);ba=nfd(b+a)
        if ab==ba:return -1 if ab==a+b else 1
        return 0
    for cp in range(0x110000):
        if unicodedata.category(chr(cp))!='Cn':continue
        c=chr(cp)
        if nfd(c)!=c:continue
        if nfd('\u0345'+c)!=c+'\u0345' and nfd(c+'\u0334')!='\u0334'+c:continue
        lo,hi=0,len(classes)
        while lo<hi:
            mid=(lo+hi)//2;order=compare(c,classes[mid][1])
            if order>0:lo=mid+1
            else:hi=mid
        if lo==len(classes) or compare(c,classes[lo][1])!=0:classes.insert(lo,(None,c))
        extra[cp]=classes[lo][1]
    rank_for_old={value:i+1 for i,(value,c) in enumerate(classes) if value is not None}
    rank_for_extra={c:i+1 for i,(_,c) in enumerate(classes)}
    ranks={cp:rank_for_old[value] for cp,value in known.items()}
    ranks.update({cp:rank_for_extra[c] for cp,c in extra.items()})
    combining = valued_ranges(lambda cp:ranks.get(cp,0))

    decomposition_data = []
    decompositions = []
    compositions = []
    for codepoint in range(0x110000):
        if 0xD800<=codepoint<=0xDFFF or 0xAC00<=codepoint<=0xD7A3:
            continue
        raw=nfd(chr(codepoint))
        if raw==chr(codepoint):continue
        sequence=tuple(map(ord,raw))
        offset = len(decomposition_data)
        decomposition_data.extend(sequence)
        decompositions.append((codepoint, offset, len(sequence)))
        if len(sequence)>=2:
            first=nfc(raw[:-1]);second=raw[-1]
            if len(first)==1 and nfc(first+second)==chr(codepoint):
                compositions.append((ord(first),ord(second),codepoint))

    print("// Generated by tools/generate_unicode_tables.py.")
    print(f"// Python lower {unicodedata.unidata_version}; Rust tokenizers {importlib.metadata.version('tokenizers')} regex/NFC.")
    print('// Combining values are ordinal ranks preserving CCC order/equality.')
    print("#pragma once")
    print("#include <cstddef>")
    print("#include <cstdint>")
    print("namespace mula::text_detail {")
    print("struct CodepointRange { std::uint32_t first; std::uint32_t last; };")
    print("struct CombiningRange { std::uint32_t first; std::uint32_t last; std::uint8_t value; };")
    print("struct Decomposition { std::uint32_t codepoint; std::uint16_t offset; std::uint8_t length; };")
    print("struct Composition { std::uint32_t first; std::uint32_t second; std::uint32_t result; };")
    print(f'inline constexpr const char unicode_version[] = "{unicodedata.unidata_version}";')
    emit_pairs("letter_ranges", letters)
    emit_pairs("number_ranges", numbers)
    print("inline constexpr CombiningRange combining_ranges[] = {")
    for first, last, value in combining:
        print(f"    {{0x{first:X}, 0x{last:X}, {value}}},")
    print("};")
    print("inline constexpr std::uint32_t decomposition_data[] = {")
    for index in range(0, len(decomposition_data), 12):
        values = ", ".join(f"0x{value:X}" for value in decomposition_data[index:index + 12])
        print(f"    {values},")
    print("};")
    print("inline constexpr Decomposition decompositions[] = {")
    for codepoint, offset, length in decompositions:
        print(f"    {{0x{codepoint:X}, {offset}, {length}}},")
    print("};")
    print("inline constexpr Composition compositions[] = {")
    for first, second, result in sorted(compositions):
        print(f"    {{0x{first:X}, 0x{second:X}, 0x{result:X}}},")
    print("};")
    def cased(cp):
        c=chr(cp);return c.islower() or c.isupper() or unicodedata.category(c)=='Lt'
    # Probe Python's own contextual sigma rule for its exact Case_Ignorable set.
    def ignorable(cp):
        c=chr(cp)
        return (c+'Σ').lower().endswith('σ') if cased(cp) else ('AΣ'+c+'A').lower()[1]=='σ'
    emit_pairs("cased_ranges", ranges_for(cased))
    emit_pairs("ignorable_ranges", ranges_for(ignorable))
    print("struct Lower { std::uint32_t from, first, second; };")
    print("inline constexpr Lower lower_map[] = {")
    for cp in range(0x110000):
        lower=chr(cp).lower()
        if lower!=chr(cp):
            assert 1<=len(lower)<=2
            print(f"    {{0x{cp:X}, 0x{ord(lower[0]):X}, 0x{ord(lower[1]) if len(lower)==2 else 0:X}}},")
    print("};")
    print("} // namespace mula::text_detail")


if __name__ == "__main__":
    main()
